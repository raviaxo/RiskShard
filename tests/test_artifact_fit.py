"""The check ADR-0024 said did not exist, and the number it corrects twice.

ADR-0024's context paragraph ends on the finding that this repo had no path
reading an audit answer against the evidence records citing the same source, and
that `engine.intake.blocked_but_held` is the near neighbour and cannot see the
class. `engine/artifact_fit.py` is that path.

Two corrections are pinned here, both of them the project's own rule landing on
its own work.

1. ADR-0024 measured the population BY HAND and said so — *"this count is not yet
   generated by anything."* It was wrong: 9 records where there are 26, and all
   Cyentia where twelve are not.

2. The first version of the check read `sources/raw/` from disk. That directory
   is deliberately not distributed, so it found 21 records locally and **zero in
   CI**, where four of these tests failed. Anything that depends on the raw corpus
   is enrichment only, and is asserted here conditionally — a check that reports a
   clean zero on every clone but one publishes reassurance, which is worse than
   reporting nothing.
"""
import unittest

from engine.artifact_fit import (artifacts_by_stem, fit_report, format_findings,
                                 sources_held_twice, summary_line)
from engine.project_paths import find_project_root

ROOT = find_project_root()


class ArtifactFitTests(unittest.TestCase):
    def setUp(self):
        self.report = fit_report(ROOT)
        self.totals = self.report["totals"]
        self.flagged = self.report["cites_a_page_for_a_report_we_hold"]

    def test_it_finds_the_record_that_started_adr_0024(self):
        """The IRIS 2025 maximum is the original defect and must stay visible."""
        ids = {e["evidence_id"] for e in self.flagged}
        self.assertIn("cyentia_iris_2025_extreme_security_incident_loss_usd", ids)

    def test_the_population_is_larger_than_the_hand_count_said(self):
        """ADR-0024 hand-sized this as 9 records. Generated, it is 26."""
        self.assertEqual(self.totals["cites_a_page_for_a_report_we_hold"], 26)
        self.assertEqual(self.totals["sources_flagged"], 7)

    def test_it_is_not_a_cyentia_problem(self):
        """ADR-0024 said all nine were Cyentia. Four other publishers are in it."""
        sources = {e["source_id"] for e in self.flagged}
        for expected in ("netdiligence_cyber_claims_2025",
                         "ponemon_dtex_cost_insider_risks_2023",
                         "sophos_state_ransomware_manufacturing_2025",
                         "ibm_cost_data_breach_2025"):
            self.assertIn(expected, sources)
        non_cyentia = [e for e in self.flagged if not e["source_id"].startswith("cyentia")]
        self.assertEqual(len(non_cyentia), 12)

    def test_it_reaches_a_record_behind_a_published_maximum(self):
        """The Sophos threshold is the anchor behind the DE and JP modeled_quantile maxima.

        Worth its own assertion because it is the answer to "is this bookkeeping?".
        A record in this population is not an abstraction — it is the evidence under
        a number the explorer publishes.
        """
        ids = {e["evidence_id"] for e in self.flagged}
        self.assertIn("sophos_manufacturing_ransomware_extreme_case_threshold_usd_2025", ids)

    def test_the_three_populations_are_not_collapsed(self):
        """Collapsing them is how the hand count went wrong."""
        self.assertGreaterEqual(self.totals["mismatched"],
                                self.totals["cites_a_page_for_a_report_we_hold"])
        self.assertGreater(self.totals["unmanifested"], 0,
                           "records with no manifest entry are unmeasured, not clean")

    def test_the_finding_does_not_depend_on_the_undistributed_corpus(self):
        """The whole population must be derivable from committed data.

        This is the assertion that would have caught the first version in review
        instead of in CI: every flagged record is decided by the manifest and the
        record, and `sources/raw/` contributes nothing to the count.
        """
        for entry in self.flagged:
            self.assertTrue(entry["stored_is_a_report"])
            self.assertNotEqual(entry["cites"], entry["stored_artifact"])

    def test_the_summary_line_carries_its_own_denominators(self):
        line = summary_line(self.report)
        self.assertIn(str(self.totals["cites_a_page_for_a_report_we_hold"]), line)
        self.assertIn(str(self.totals["unmanifested"]), line)

    def test_the_findings_listing_names_every_flagged_record(self):
        listing = format_findings(self.report)
        for entry in self.flagged:
            self.assertIn(entry["evidence_id"], listing)


class LocalCorpusTests(unittest.TestCase):
    """Everything that needs `sources/raw/`, skipped where it is absent.

    `sources/raw/` holds large third-party PDFs and is not distributed. These
    assertions describe the maintainer's machine, so they skip rather than fail —
    and the count they check is reported as `None` elsewhere, never as 0, so
    nobody reads "we did not look" as "we looked and found none".
    """

    def setUp(self):
        if not artifacts_by_stem(ROOT):
            self.skipTest("sources/raw/ is not present — the corpus is not distributed")

    def test_a_source_held_twice_is_found_by_shape_not_by_a_list(self):
        held = sources_held_twice(ROOT)
        self.assertTrue(held)
        for suffixes in held.values():
            self.assertTrue(any(s in suffixes for s in (".pdf", ".xlsx", ".csv")))
            self.assertTrue(any(s in suffixes for s in (".html", ".htm")))

    def test_the_xlsx_case_counts_as_a_report(self):
        """census_susb_2022 is held as a page and a spreadsheet.

        ADR-0024 counted PDFs only. A published data table beside its landing page
        is the same shape, so it counts here.
        """
        self.assertIn("census_susb_2022", sources_held_twice(ROOT))


class DoctorIntegrationTests(unittest.TestCase):
    def test_the_doctor_reports_artifact_fit_every_run(self):
        """It reports and never gates — a landing page can be a fair permalink."""
        from engine.doctor import build_doctor_report

        checks = {c["name"]: c for c in build_doctor_report(ROOT)["checks"]}
        self.assertIn("artifact fit", checks)
        self.assertEqual(checks["artifact fit"]["status"], "pass")
        self.assertIn("other than the report we hold", checks["artifact fit"]["detail"])


if __name__ == "__main__":
    unittest.main()
