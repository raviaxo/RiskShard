"""The check ADR-0024 said did not exist, and the number it corrects.

ADR-0024's context paragraph ends on the finding that this repo had no path
reading an audit answer against the evidence records citing the same source,
and that `engine.intake.blocked_but_held` is the near neighbour and cannot see
the class. `engine/artifact_fit.py` is that path. These tests pin what it found.

The sizing matters more than it looks. ADR-0024 measured the population BY HAND
and said so — *"this count is not yet generated by anything"* — and the hand
count was wrong twice over: it said 9 records where there are 21, and said all
of them were Cyentia when 7 are not. That is the project's own rule arriving on
the project's own ADR, so the number now has an owner and these assertions are
it.
"""
import unittest

from engine.artifact_fit import (fit_report, format_findings, sources_held_twice,
                                 summary_line)
from engine.project_paths import find_project_root

ROOT = find_project_root()


class ArtifactFitTests(unittest.TestCase):
    def setUp(self):
        self.report = fit_report(ROOT)
        self.totals = self.report["totals"]

    def test_it_finds_the_record_that_started_adr_0024(self):
        """The IRIS 2025 maximum is the original defect and must stay visible."""
        flagged = {e["evidence_id"] for e in self.report["read_the_thinner_artifact"]}
        self.assertIn("cyentia_iris_2025_extreme_security_incident_loss_usd", flagged)

    def test_the_population_is_larger_than_the_hand_count_said(self):
        """ADR-0024 hand-sized this as 9 records. Generated, it is 21.

        Asserted as a floor plus an exact value rather than a bare number so a
        future re-read that CLEARS records fails loudly here and has to update
        the ADR too, instead of quietly shrinking a published figure.
        """
        self.assertEqual(self.totals["read_the_thinner_artifact"], 21)

    def test_it_is_not_a_cyentia_problem(self):
        """ADR-0024 said all nine were Cyentia. Two other publishers are in it."""
        sources = {e["source_id"] for e in self.report["read_the_thinner_artifact"]}
        self.assertIn("netdiligence_cyber_claims_2025", sources)
        self.assertIn("ponemon_dtex_cost_insider_risks_2023", sources)
        non_cyentia = [e for e in self.report["read_the_thinner_artifact"]
                       if not e["source_id"].startswith("cyentia")]
        self.assertEqual(len(non_cyentia), 7)

    def test_a_source_held_twice_is_found_by_shape_not_by_a_list(self):
        """No hard-coded stem list — the pairs are discovered from what is on disk."""
        held = sources_held_twice(ROOT)
        self.assertEqual(len(held), self.totals["sources_held_twice"])
        for suffixes in held.values():
            self.assertTrue(any(s in suffixes for s in (".pdf", ".xlsx", ".csv")))
            self.assertTrue(any(s in suffixes for s in (".html", ".htm")))

    def test_the_xlsx_case_counts_as_a_report(self):
        """census_susb_2022 is held as a page and a spreadsheet.

        ADR-0024 counted PDFs only and found six pairs. A published data table
        beside its landing page is the same defect shape, so the module counts
        it and the totals differ from the ADR by exactly that one source. It
        contributes no flagged record today, which is why it is asserted here
        rather than left to be noticed as a discrepancy later.
        """
        self.assertIn("census_susb_2022", sources_held_twice(ROOT))

    def test_the_three_populations_are_not_collapsed(self):
        """Collapsing them is how the hand count went wrong."""
        self.assertGreaterEqual(self.totals["mismatched"],
                                self.totals["read_the_thinner_artifact"])
        self.assertGreater(self.totals["unmanifested"], 0,
                           "records with no manifest entry are unmeasured, not clean")

    def test_the_summary_line_carries_its_own_denominators(self):
        line = summary_line(self.report)
        self.assertIn(str(self.totals["read_the_thinner_artifact"]), line)
        self.assertIn(str(self.totals["sources_held_twice"]), line)
        self.assertIn(str(self.totals["unmanifested"]), line)

    def test_the_findings_listing_names_every_flagged_record(self):
        listing = format_findings(self.report)
        for entry in self.report["read_the_thinner_artifact"]:
            self.assertIn(entry["evidence_id"], listing)


class DoctorIntegrationTests(unittest.TestCase):
    def test_the_doctor_reports_artifact_fit_every_run(self):
        """It reports and never gates — a landing page can be a fair permalink."""
        from engine.doctor import build_doctor_report

        checks = {c["name"]: c for c in build_doctor_report(ROOT)["checks"]}
        self.assertIn("artifact fit", checks)
        self.assertEqual(checks["artifact fit"]["status"], "pass")
        self.assertIn("cite a page while a report", checks["artifact fit"]["detail"])


if __name__ == "__main__":
    unittest.main()
