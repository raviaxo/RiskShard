"""The README's strength table is generated, so it is checked against a fresh render.

`README.md` carries the progress ledger between `<!-- strength-ledger:begin -->` and
`<!-- strength-ledger:end -->`, written by `engine.strength_ledger.update_readme_progress`
from `docs/internal/strength_ledger.json`. It is the public face of *"data strength is
tracked, not asserted"* — fifteen rows of source-backed counts, cell-matched counts and
shard totals, one per data-pack release.

**Generated and unwatched is the defect this repository has now hit four times.** A
calibration summary stood on an edition it had moved off five weeks earlier (#199). A
release archive was never built, so the current release's pinned citation 404'd (#202).
`docs/EVIDENCE_REPORT.md` was five weeks stale, publishing a parameter value that
fourteen tests had already moved (#203). In every case the artifact was generated, the
generation was a manual release step, and nothing failed when the step was skipped.
The close note for that session named the pattern and said where to look next:

> *If a fourth exists, it is another artifact regenerated by hand at release time; that
> is the place to look first.*

This is that artifact. It was **current** when this test was written on 2026-10-26 — so
this is preventive, not a fix — and it was unguarded, which is the same position the
other three were in on the day before each of them went stale.

**Why it matters more at the next release than it did at the last one.** The first
release on or after 2026-11-01 is where [ADR-0017](../docs/adr/0017-the-kill-criterion-gets-a-clock.md)
re-measures the registry kill criterion, and it adds a row to this table. A release that
publishes a measured kill decision while carrying a stale strength table would undercut
the one claim the measurement is for.

The assertion is equality against a fresh render rather than a spot-check of figures a
person listed, for the same reason `test_evidence_report_is_current.py` gives: the file
is entirely generated, so a test watching only the numbers someone remembered to name
would miss everything else that moves with them.
"""

import shutil
import tempfile
import unittest
from pathlib import Path

from engine.strength_ledger import update_readme_progress

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
LEDGER = ROOT / "docs" / "internal" / "strength_ledger.json"

# The begin marker carries a regenerate hint after the name, so it is matched by prefix.
BEGIN = "<!-- strength-ledger:begin"
END = "<!-- strength-ledger:end -->"


class ReadmeProgressTableIsCurrent(unittest.TestCase):
    def test_markers_are_present(self):
        """Without the markers the writer raises, and the table silently stops updating."""
        text = README.read_text(encoding="utf-8")
        self.assertIn(BEGIN, text, "the strength-ledger begin marker is gone from README.md")
        self.assertIn(END, text, "the strength-ledger end marker is gone from README.md")
        self.assertLess(text.index(BEGIN), text.index(END), "the markers are inverted")

    def test_committed_table_equals_a_fresh_render(self):
        """Regenerating from the committed ledger must change nothing."""
        with tempfile.TemporaryDirectory() as tmp:
            candidate = Path(tmp) / "README.md"
            shutil.copy(README, candidate)
            update_readme_progress(candidate, LEDGER)
            self.assertEqual(
                README.read_text(encoding="utf-8"),
                candidate.read_text(encoding="utf-8"),
                "README.md's strength table does not match a fresh render from "
                "docs/internal/strength_ledger.json. Regenerate it as part of the "
                "release — do not hand-edit the rows.",
            )

    def test_every_ledger_release_has_a_row(self):
        """A row count that drifts from the ledger means a release was recorded in one
        place and not the other, which is how the table would go stale one row at a time
        rather than all at once."""
        import json

        ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
        entries = ledger if isinstance(ledger, list) else (
            ledger.get("releases") or ledger.get("entries") or []
        )
        body = README.read_text(encoding="utf-8").split(BEGIN, 1)[1].split(END, 1)[0]
        rows = [
            line for line in body.split("\n")
            if line.startswith("| 20") and line.count("|") >= 6
        ]
        self.assertEqual(
            len(rows),
            len(entries),
            f"the ledger holds {len(entries)} releases and the README table shows "
            f"{len(rows)} rows",
        )


if __name__ == "__main__":
    unittest.main()
