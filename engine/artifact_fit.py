"""Does an evidence record cite the artifact the audit actually read?

[ADR-0024](../docs/adr/0024-the-published-bracket.md) found a defect no check in
this repo could see. `sources/audit.yaml` had read Cyentia's IRIS 2025 **report**
and quoted its 95th-percentile sentence; the evidence record anchoring a maximum
on that same source had been extracted two months earlier from the publisher's
4,113-character **summary page**, and carried `exceedance_basis: none_known` with
a caveat saying no percentile was available. Both surfaces were governed, both
were pinned, and they held contradictory answers about the same source for 88
days because **nothing read one against the other.**

`engine.intake.blocked_but_held` is the near neighbour and structurally cannot
catch it. That check asks whether a source the audit calls unreadable has a
candidate document on disk. Here the source was registered, held, and verified
against the report on all four audit properties. Nothing was blocked, missing or
unread. The question this module asks instead is narrower:

    Does this record cite the report we hold, or something else
    the publisher also put on the web?

A mismatch is **not automatically a defect.** A landing page is often the only
citable permalink, and a record read from the report may reasonably cite the page
a reader can actually open. What makes it worth flagging is the pair: the record
cites something other than the stored artifact *while the stored artifact is a
full report*, because then the richer document was in hand and the extraction
did not cite it.

**The signal is derived from the manifest, not from the disk, and that was
learned the hard way.** The first version of this module grouped the files in
`sources/raw/` by stem and looked for stems holding both a page and a report. It
found 21 records on the maintainer's machine and **zero everywhere else** —
`sources/raw/` holds large third-party PDFs and is deliberately not distributed,
so CI read an empty directory and four assertions failed. A check that reports a
clean zero on every clone but one is worse than no check, because it publishes
reassurance.

Asking the question of committed data turns out to be the better question too.
The disk version could only flag a source whose page we also happened to gather,
which is an accident of collection rather than a property of the defect. The
manifest version finds the record that cites a page for a report we hold whether
or not anyone archived that page.

**What it measured, 2026-11-14.** ADR-0024 sized this by hand as *"9 of the 21
cite the page rather than the report, and all 9 are Cyentia."* Generated, it is
**26 records across 7 sources, and 12 are not Cyentia** — five NetDiligence, four
Sophos, two Ponemon/DTEX and one IBM. The ADR flagged that count as not yet
generated by anything, which is exactly why it was wrong, and is the reason this
module exists rather than a sentence in a document.
"""
import collections
import json
from pathlib import Path

from engine.project_paths import find_project_root

MANIFEST_RELPATH = Path("sources") / "manifest.json"

# Suffixes that carry a publisher's full document rather than a page about it.
REPORT_SUFFIXES = (".pdf", ".xlsx", ".csv")
PAGE_SUFFIXES = (".html", ".htm")


def load_manifest(root=None):
    root = Path(root or find_project_root())
    path = root / MANIFEST_RELPATH
    if not path.is_file():
        return {}
    return {s["id"]: s for s in json.loads(path.read_text(encoding="utf-8"))["sources"]}


def stored_is_a_report(source):
    """Is the artifact we stored for this source the publisher's full document?"""
    return (source.get("raw_path") or "").lower().endswith(REPORT_SUFFIXES)


def artifacts_by_stem(root=None):
    """Stored artifacts grouped by stem. **Local only** — `sources/raw/` is not distributed.

    Never let a conclusion rest on this. It is returned as enrichment for whoever
    is standing at the machine that holds the corpus, and `fit_report` reports
    whether it was available rather than treating absence as absence of defects.
    """
    root = Path(root or find_project_root())
    raw = root / "sources" / "raw"
    grouped = collections.defaultdict(set)
    if not raw.is_dir():
        return grouped
    for path in raw.iterdir():
        if path.is_file():
            grouped[path.stem].add(path.suffix.lower())
    return grouped


def sources_held_twice(root=None):
    """Stems holding both a page and a report. **Local only** — see `artifacts_by_stem`."""
    return {
        stem: sorted(suffixes)
        for stem, suffixes in artifacts_by_stem(root).items()
        if any(s in suffixes for s in REPORT_SUFFIXES)
        and any(s in suffixes for s in PAGE_SUFFIXES)
    }


def fit_report(root=None, records=None):
    """Compare what each evidence record cites against what was stored for it.

    Three populations, because they answer different questions and collapsing
    them is how ADR-0024's hand count went wrong:

      `unmanifested` — the source has no manifest entry, so there is nothing to
        compare and the record is **unmeasured rather than clean**.
      `mismatched` — the record cites something other than the stored artifact.
        Often benign; a landing page is a fair permalink.
      `cites_a_page_for_a_report_we_hold` — mismatched AND the stored artifact is
        a full report. This is the population ADR-0024's defect came from, and
        the only one any conclusion should rest on.
    """
    root = Path(root or find_project_root())
    if records is None:
        from engine.tail_bracket import load_evidence_records
        records = load_evidence_records()

    manifest = load_manifest(root)
    held_twice = sources_held_twice(root)
    raw_available = bool(artifacts_by_stem(root))

    unmanifested, mismatched, flagged = [], [], []
    for record in records:
        source = manifest.get(record.get("source_id"))
        if source is None:
            unmanifested.append(record["id"])
            continue
        cited = record.get("source_url_or_citation") or ""
        stored = source.get("final_url") or ""
        if cited == stored:
            continue
        entry = {
            "evidence_id": record["id"],
            "source_id": record["source_id"],
            "cites": cited,
            "stored_artifact": stored,
            "stored_is_a_report": stored_is_a_report(source),
            "page_also_held": Path(source.get("raw_path") or "").stem in held_twice,
        }
        mismatched.append(entry)
        if entry["stored_is_a_report"]:
            flagged.append(entry)

    return {
        "records": len(records),
        "raw_available": raw_available,
        "sources_held_twice": held_twice,
        "unmanifested": sorted(unmanifested),
        "mismatched": mismatched,
        "cites_a_page_for_a_report_we_hold": flagged,
        "totals": {
            "records": len(records),
            "unmanifested": len(unmanifested),
            "mismatched": len(mismatched),
            "cites_a_page_for_a_report_we_hold": len(flagged),
            "sources_flagged": len({e["source_id"] for e in flagged}),
            # Local-only. None, not 0, when sources/raw/ is absent — so a reader
            # can tell "we did not look" from "we looked and found none".
            "sources_held_twice": len(held_twice) if raw_available else None,
        },
    }


def summary_line(report):
    """One line for the doctor. Reports, never gates — a permalink can be a page."""
    totals = report["totals"]
    held = totals["sources_held_twice"]
    held_text = (f"{held} source(s) are held as both a page and a report"
                 if held is not None
                 else "sources/raw/ not present, so the page-also-held count is unmeasured")
    return (
        f"{totals['cites_a_page_for_a_report_we_hold']} evidence record(s) cite something "
        f"other than the report we hold, across {totals['sources_flagged']} source(s); "
        f"{totals['mismatched']} record(s) cite something other than the stored artifact; "
        f"{totals['unmanifested']} record(s) have no manifest entry to compare against; "
        f"{held_text}"
    )


def format_findings(report):
    """A human-readable listing, grouped by source."""
    by_source = collections.defaultdict(list)
    for entry in report["cites_a_page_for_a_report_we_hold"]:
        by_source[entry["source_id"]].append(entry["evidence_id"])
    lines = []
    for source_id, ids in sorted(by_source.items()):
        lines.append(f"{source_id} ({len(ids)} record(s))")
        lines.extend(f"  - {i}" for i in sorted(ids))
    return "\n".join(lines)
