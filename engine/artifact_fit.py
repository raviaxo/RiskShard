"""Does an evidence record cite the artifact the audit actually read?

[ADR-0024](../docs/adr/0024-the-published-bracket.md) found a defect no check in
this repo could see. `sources/audit.yaml` had read Cyentia's IRIS 2025 **report**
and quoted its 95th-percentile sentence; the evidence record anchoring a maximum
on that same source had been extracted two months earlier from the publisher's
4,113-character **summary page**, and carried `exceedance_basis: none_known` with
a caveat saying no percentile was available. Both surfaces were governed, both
were pinned, and they held contradictory answers about the same source for 88
days because **nothing read one against the other.**

`engine.intake.blocked_but_held` is the near neighbour and structurally cannot
catch it. That check asks whether a source the audit calls unreadable has a
candidate document on disk. Here the source is registered, held, and verified
against the report on all four audit properties. Nothing was blocked, missing or
unread. The question this module asks instead is narrower and, it turns out,
more common:

    Does this record cite the artifact that was stored and verified,
    or something else the publisher also put on the web?

A mismatch is **not automatically a defect.** A landing page is often the only
citable permalink, and a record read from the report may reasonably cite the
page a reader can actually open. What makes it a defect is the pair: the record
cites a page *while a report-grade artifact of the same source is held on disk*,
because then the richer document was available and the extraction did not use
it. That pair is what this module counts, and it is deliberately the narrow
reading — see `fit_report()['mismatched']` for the wider one.

**What it measured on its first run, 2026-11-14.** ADR-0024 sized this by hand
as *"9 of the 21 cite the page rather than the report, and all 9 are Cyentia."*
Generated, it is **21 of 21, and 7 are not Cyentia** — five NetDiligence and two
Ponemon/DTEX. The ADR labelled that count as not yet generated by anything,
which is exactly why it was wrong, and is the reason this module exists rather
than a sentence in a document.
"""
import collections
import json
from pathlib import Path

from engine.project_paths import find_project_root

RAW_DIRNAME = "raw"
MANIFEST_RELPATH = Path("sources") / "manifest.json"

# Suffixes that carry a publisher's full document, in descending richness. A stem
# holding one of these AND a page artifact is a source we hold twice.
REPORT_SUFFIXES = (".pdf", ".xlsx", ".csv")
PAGE_SUFFIXES = (".html", ".htm")


def artifacts_by_stem(root=None):
    """Every stored artifact on disk, grouped by the stem that names its source."""
    root = Path(root or find_project_root())
    raw = root / "sources" / RAW_DIRNAME
    grouped = collections.defaultdict(set)
    if not raw.is_dir():
        return grouped
    for path in raw.iterdir():
        if path.is_file():
            grouped[path.stem].add(path.suffix.lower())
    return grouped


def sources_held_twice(root=None):
    """Stems holding both a page and a report — the corpus's duplicate-artifact set."""
    grouped = artifacts_by_stem(root)
    return {
        stem: sorted(suffixes)
        for stem, suffixes in grouped.items()
        if any(s in suffixes for s in REPORT_SUFFIXES)
        and any(s in suffixes for s in PAGE_SUFFIXES)
    }


def load_manifest(root=None):
    root = Path(root or find_project_root())
    path = root / MANIFEST_RELPATH
    if not path.is_file():
        return {}
    return {s["id"]: s for s in json.loads(path.read_text(encoding="utf-8"))["sources"]}


def fit_report(root=None, records=None):
    """Compare what each evidence record cites against what was stored for it.

    Returns three populations, because they answer different questions and
    collapsing them is how the hand count went wrong:

      `unmanifested` — the record's source has no manifest entry, so there is
        nothing to compare and this is unmeasured rather than clean.
      `mismatched` — the record cites something other than the stored artifact.
        Often benign; a landing page is a fair permalink.
      `read_the_thinner_artifact` — mismatched AND the source is held twice, so a
        report was on disk and the extraction cites the page instead. This is the
        population ADR-0024's defect came from.
    """
    root = Path(root or find_project_root())
    if records is None:
        from engine.tail_bracket import load_evidence_records
        records = load_evidence_records()

    manifest = load_manifest(root)
    held_twice = sources_held_twice(root)

    unmanifested, mismatched, thinner = [], [], []
    for record in records:
        source = manifest.get(record.get("source_id"))
        if source is None:
            unmanifested.append(record["id"])
            continue
        cited = record.get("source_url_or_citation") or ""
        stored = source.get("final_url") or ""
        if cited == stored:
            continue
        stem = Path(source.get("raw_path") or "").stem
        entry = {
            "evidence_id": record["id"],
            "source_id": record["source_id"],
            "cites": cited,
            "stored_artifact": stored,
            "held": held_twice.get(stem, []),
        }
        mismatched.append(entry)
        if stem in held_twice:
            thinner.append(entry)

    return {
        "records": len(records),
        "sources_held_twice": held_twice,
        "unmanifested": sorted(unmanifested),
        "mismatched": mismatched,
        "read_the_thinner_artifact": thinner,
        "totals": {
            "records": len(records),
            "sources_held_twice": len(held_twice),
            "unmanifested": len(unmanifested),
            "mismatched": len(mismatched),
            "read_the_thinner_artifact": len(thinner),
        },
    }


def summary_line(report):
    """One line for the doctor. Reports, never gates — see `format_findings`."""
    totals = report["totals"]
    publishers = sorted({e["source_id"] for e in report["read_the_thinner_artifact"]})
    return (
        f"{totals['read_the_thinner_artifact']} evidence record(s) cite a page while a "
        f"report of the same source is held on disk, across {len(publishers)} source(s); "
        f"{totals['sources_held_twice']} source(s) are held twice; "
        f"{totals['mismatched']} record(s) cite something other than the stored artifact; "
        f"{totals['unmanifested']} record(s) have no manifest entry to compare against"
    )


def format_findings(report):
    """A human-readable listing, grouped by source."""
    by_source = collections.defaultdict(list)
    for entry in report["read_the_thinner_artifact"]:
        by_source[entry["source_id"]].append(entry["evidence_id"])
    lines = []
    for source_id, ids in sorted(by_source.items()):
        lines.append(f"{source_id} ({len(ids)} record(s))")
        lines.extend(f"  - {i}" for i in sorted(ids))
    return "\n".join(lines)
